using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using VisionCore.Security;

namespace VisionCore.Telemetry;

public enum FaultCategory
{
    General,
    Camera,
    PlcCommunication,
    NativeEngine,
    ToolExecution,
    AssetVault,
    SystemResources,
    Configuration
}

public sealed record SystemMetricsSnapshot
{
    public string Os { get; init; } = Environment.OSVersion.ToString();
    public string Clr { get; init; } = Environment.Version.ToString();
    public double ProcessMemoryMb { get; init; } = Math.Round(GC.GetTotalMemory(false) / (1024.0 * 1024.0), 2);
    public double WorkingSetMb { get; init; } = Math.Round(Environment.WorkingSet / (1024.0 * 1024.0), 2);
    public int ProcessorCount { get; init; } = Environment.ProcessorCount;
    public double UptimeSeconds { get; init; } = Math.Round(Environment.TickCount64 / 1000.0, 1);
}

public sealed record PipelineContextSnapshot
{
    public string ActiveToolName { get; init; } = "Unknown";
    public string SafeToolLabel { get; init; } = "Pattern Match";
    public string FrameResolution { get; init; } = "2592x1944";
    public int ExposureUs { get; init; } = 1200;
    public double GainDb { get; init; } = 6.0;
    public IReadOnlyList<string> RecentEvents { get; init; } = Array.Empty<string>();
}

/// <summary>
/// A standardized diagnostic bundle generated by the vision system whenever an error,
/// fault, timeout, or exception occurs. Formatted so the user can directly copy and paste
/// it into Claude to get an immediate, actionable fix.
/// </summary>
public sealed class ClaudeDiagnosticPackage
{
    public string IncidentId { get; init; } = $"INC-{DateTime.UtcNow:yyyyMMddHHmmss}-{Random.Shared.Next(1000, 9999)}";
    public DateTime TimestampUtc { get; init; } = DateTime.UtcNow;
    public string Facility { get; init; } = "Sundaram Enterprise";
    public string Line { get; init; } = "Line 01";
    public string Station { get; init; } = "Station 01";
    public string SoftwareVersion { get; init; } = "v2.4.0-pilot";
    public FaultCategory FaultCategory { get; init; } = FaultCategory.General;
    public string FaultCode { get; init; } = "ERR_UNHANDLED_EXCEPTION";
    public string ExceptionType { get; init; } = "System.Exception";
    public string ErrorMessage { get; init; } = "An unexpected error occurred.";
    public string StackTrace { get; init; } = "";
    public SystemMetricsSnapshot SystemMetrics { get; init; } = new();
    public PipelineContextSnapshot PipelineContext { get; init; } = new();
    public string? DiagnosticHint { get; init; }

    /// <summary>
    /// Creates a diagnostic package from an exception and operational context.
    /// Uses CamouflageLabels to safeguard proprietary algorithm names.
    /// </summary>
    public static ClaudeDiagnosticPackage Create(
        Exception ex,
        string facility,
        string line,
        string station,
        FaultCategory category,
        string faultCode,
        string? rawToolName = null,
        IReadOnlyList<string>? recentEvents = null,
        string? diagnosticHint = null)
    {
        string rawTool = rawToolName ?? "Unknown";
        string safeTool = CamouflageLabels.GetSafeToolLabel(rawTool);

        return new ClaudeDiagnosticPackage
        {
            IncidentId = $"INC-{DateTime.UtcNow:yyyyMMdd}-{facility.Replace(" ", "").ToUpperInvariant()[..Math.Min(4, facility.Length)]}-{Random.Shared.Next(1000, 9999):X4}",
            TimestampUtc = DateTime.UtcNow,
            Facility = facility,
            Line = line,
            Station = station,
            FaultCategory = category,
            FaultCode = faultCode,
            ExceptionType = ex.GetType().FullName ?? ex.GetType().Name,
            ErrorMessage = ex.Message,
            StackTrace = ex.StackTrace ?? "",
            DiagnosticHint = diagnosticHint,
            SystemMetrics = new SystemMetricsSnapshot(),
            PipelineContext = new PipelineContextSnapshot
            {
                ActiveToolName = safeTool, // IP protection: never disclose internal tool name
                SafeToolLabel = safeTool,
                RecentEvents = recentEvents ?? Array.Empty<string>()
            }
        };
    }

    /// <summary>
    /// Calculates a stable signature for grouping similar errors across lines and plants.
    /// Removes line numbers, addresses, and variable tokens from the stack trace.
    /// </summary>
    public string CalculateSignature()
    {
        var sb = new StringBuilder();
        sb.Append(FaultCategory).Append('|');
        sb.Append(FaultCode).Append('|');
        sb.Append(ExceptionType).Append('|');

        if (!string.IsNullOrWhiteSpace(StackTrace))
        {
            string[] lines = StackTrace.Split(new[] { '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
            int frames = 0;
            foreach (string line in lines)
            {
                if (frames >= 3) break;
                string cleanLine = System.Text.RegularExpressions.Regex.Replace(line, @":line \d+", ":line X");
                cleanLine = System.Text.RegularExpressions.Regex.Replace(cleanLine, @"0x[0-9a-fA-F]+", "0xADDR");
                sb.Append(cleanLine.Trim()).Append(';');
                frames++;
            }
        }
        else
        {
            sb.Append(ErrorMessage);
        }

        byte[] hash = SHA256.HashData(Encoding.UTF8.GetBytes(sb.ToString()));
        return $"CLUST-{Convert.ToHexString(hash)[..12]}";
    }

    /// <summary>
    /// Generates the copy-paste markdown prompt specifically engineered for Claude.
    /// </summary>
    public string ToClaudeMarkdownPrompt()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# CLAUDE DIAGNOSTIC REPORT: VISION SYSTEM INCIDENT");
        sb.AppendLine($"> **Auto-generated by Sundaram Vision Telemetry** on `{TimestampUtc:yyyy-MM-dd HH:mm:ss} UTC`");
        sb.AppendLine();
        sb.AppendLine("## 1. Incident Metadata");
        sb.AppendLine($"- **Incident ID**: `{IncidentId}`");
        sb.AppendLine($"- **Location**: `{Facility}` / `{Line}` / `{Station}`");
        sb.AppendLine($"- **Software Version**: `{SoftwareVersion}`");
        sb.AppendLine($"- **Fault Category**: `{FaultCategory}` (`{FaultCode}`)");
        sb.AppendLine($"- **Cluster Fingerprint**: `{CalculateSignature()}`");
        sb.AppendLine();
        sb.AppendLine("## 2. Problem Summary");
        sb.AppendLine($"> **{ExceptionType}**: {ErrorMessage}");
        if (!string.IsNullOrWhiteSpace(DiagnosticHint))
        {
            sb.AppendLine();
            sb.AppendLine($"> [!NOTE] System Diagnostic Hint: {DiagnosticHint}");
        }
        sb.AppendLine();
        sb.AppendLine("## 3. Hardware & Environmental Telemetry");
        sb.AppendLine($"- **OS**: `{SystemMetrics.Os}`");
        sb.AppendLine($"- **CLR**: `.NET {SystemMetrics.Clr}` ({SystemMetrics.ProcessorCount} Cores)");
        sb.AppendLine($"- **Managed Heap**: `{SystemMetrics.ProcessMemoryMb} MB` | **Working Set**: `{SystemMetrics.WorkingSetMb} MB`");
        sb.AppendLine($"- **Host Uptime**: `{TimeSpan.FromSeconds(SystemMetrics.UptimeSeconds):d\\.hh\\:mm\\:ss}`");
        sb.AppendLine($"- **Inspection Tool**: `{PipelineContext.SafeToolLabel}`");
        sb.AppendLine($"- **Camera Frame**: `{PipelineContext.FrameResolution}` (Exposure: `{PipelineContext.ExposureUs} µs`, Gain: `{PipelineContext.GainDb:F1} dB`)");
        sb.AppendLine();
        sb.AppendLine("## 4. Exception Stack Trace");
        sb.AppendLine("```csharp");
        sb.AppendLine(string.IsNullOrWhiteSpace(StackTrace) ? "(No stack trace captured)" : StackTrace);
        sb.AppendLine("```");
        sb.AppendLine();
        if (PipelineContext.RecentEvents.Count > 0)
        {
            sb.AppendLine("## 5. Recent System Events Prior to Failure");
            for (int i = 0; i < PipelineContext.RecentEvents.Count; i++)
            {
                sb.AppendLine($"{i + 1}. `{PipelineContext.RecentEvents[i]}`");
            }
            sb.AppendLine();
        }
        sb.AppendLine("## 6. Actionable Instructions for Claude");
        sb.AppendLine("Please resolve this incident by performing the following:");
        sb.AppendLine("1. **Root Cause Analysis**: Analyze the stack trace, error code, and telemetry to explain why this fault occurred.");
        sb.AppendLine("2. **Line Safety Check**: Verify the failure behavior adheres to the industrial fail-safe rule (zero false accepts, fail-safe to NG).");
        sb.AppendLine("3. **Drop-in Code Fix**: Provide the exact C# or C++ code changes required to eliminate this issue and prevent recurrences.");
        sb.AppendLine("4. **Unit Test**: Include a regression unit test to verify that the fix correctly catches and handles this scenario.");

        return sb.ToString();
    }

    public string ToJson(bool indented = true)
    {
        return JsonSerializer.Serialize(this, new JsonSerializerOptions
        {
            WriteIndented = indented,
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull
        });
    }
}
