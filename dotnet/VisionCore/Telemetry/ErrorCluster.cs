using System.Text;

namespace VisionCore.Telemetry;

public enum ClusterSeverity
{
    Warning,
    Medium,
    High,
    Critical
}

public enum ClusterStatus
{
    New,
    Investigating,
    FixScheduled,
    Resolved
}

/// <summary>
/// A cluster of identical or similar errors grouped automatically by fingerprint.
/// Aggregates occurrences across multiple plants (e.g. Sundaram Chennai, Sundaram Hosur, Sundaram Pune)
/// and lines, tracking frequency and providing an aggregated prompt for Claude.
/// </summary>
public sealed class ErrorCluster
{
    public string ClusterId { get; init; } = "";
    public string Title { get; init; } = "";
    public FaultCategory FaultCategory { get; init; } = FaultCategory.General;
    public string FaultCode { get; init; } = "";
    public string ExceptionType { get; init; } = "";
    public ClusterSeverity Severity { get; set; } = ClusterSeverity.Medium;
    public ClusterStatus Status { get; set; } = ClusterStatus.New;
    public int TotalOccurrences { get; set; } = 1;
    public DateTime FirstSeenUtc { get; set; } = DateTime.UtcNow;
    public DateTime LastSeenUtc { get; set; } = DateTime.UtcNow;
    public HashSet<string> AffectedFacilities { get; } = new(StringComparer.OrdinalIgnoreCase);
    public HashSet<string> AffectedLines { get; } = new(StringComparer.OrdinalIgnoreCase);
    public string RepresentativeStackTrace { get; set; } = "";
    public List<ClaudeDiagnosticPackage> RecentIncidents { get; } = new();

    public static ErrorCluster Create(ClaudeDiagnosticPackage incident)
    {
        var cluster = new ErrorCluster
        {
            ClusterId = incident.CalculateSignature(),
            Title = $"{incident.FaultCode}: {incident.ExceptionType} ({incident.ErrorMessage})",
            FaultCategory = incident.FaultCategory,
            FaultCode = incident.FaultCode,
            ExceptionType = incident.ExceptionType,
            FirstSeenUtc = incident.TimestampUtc,
            LastSeenUtc = incident.TimestampUtc,
            TotalOccurrences = 1,
            RepresentativeStackTrace = incident.StackTrace,
            Severity = DetermineSeverity(incident.FaultCategory, incident.FaultCode)
        };

        cluster.AffectedFacilities.Add(incident.Facility);
        cluster.AffectedLines.Add($"{incident.Facility} / {incident.Line}");
        cluster.RecentIncidents.Add(incident);
        return cluster;
    }

    public void AddIncident(ClaudeDiagnosticPackage incident)
    {
        TotalOccurrences++;
        if (incident.TimestampUtc > LastSeenUtc)
        {
            LastSeenUtc = incident.TimestampUtc;
        }
        if (incident.TimestampUtc < FirstSeenUtc)
        {
            FirstSeenUtc = incident.TimestampUtc;
        }

        AffectedFacilities.Add(incident.Facility);
        AffectedLines.Add($"{incident.Facility} / {incident.Line}");

        if (RecentIncidents.Count >= 20)
        {
            RecentIncidents.RemoveAt(0);
        }
        RecentIncidents.Add(incident);

        // Update representative stack trace if previous was empty
        if (string.IsNullOrWhiteSpace(RepresentativeStackTrace) && !string.IsNullOrWhiteSpace(incident.StackTrace))
        {
            RepresentativeStackTrace = incident.StackTrace;
        }

        // Auto-elevate severity if occurrence count spikes
        if (TotalOccurrences > 50 && Severity < ClusterSeverity.Critical)
        {
            Severity = ClusterSeverity.Critical;
        }
        else if (TotalOccurrences > 10 && Severity < ClusterSeverity.High)
        {
            Severity = ClusterSeverity.High;
        }
    }

    private static ClusterSeverity DetermineSeverity(FaultCategory category, string faultCode)
    {
        if (faultCode.Contains("CRASH", StringComparison.OrdinalIgnoreCase) ||
            faultCode.Contains("FATAL", StringComparison.OrdinalIgnoreCase) ||
            category == FaultCategory.NativeEngine)
        {
            return ClusterSeverity.Critical;
        }

        if (category == FaultCategory.Camera || category == FaultCategory.PlcCommunication)
        {
            return ClusterSeverity.High;
        }

        if (category == FaultCategory.ToolExecution)
        {
            return ClusterSeverity.Medium;
        }

        return ClusterSeverity.Warning;
    }

    /// <summary>
    /// Generates an aggregated prompt for Claude representing this entire cluster
    /// across all affected plants and lines.
    /// </summary>
    public string ToAggregatedClaudePrompt()
    {
        var sb = new StringBuilder();
        sb.AppendLine("# CLAUDE DIAGNOSTIC REPORT: AGGREGATED ENTERPRISE INCIDENT CLUSTER");
        sb.AppendLine($"> **Generated by Sundaram Admin Portal** on `{DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} UTC`");
        sb.AppendLine();
        sb.AppendLine("## 1. Cluster Overview");
        sb.AppendLine($"- **Cluster Fingerprint**: `{ClusterId}`");
        sb.AppendLine($"- **Title**: `{Title}`");
        sb.AppendLine($"- **Severity**: `{Severity}`");
        sb.AppendLine($"- **Status**: `{Status}`");
        sb.AppendLine($"- **Total Occurrences**: **{TotalOccurrences:N0}**");
        sb.AppendLine($"- **First Observed**: `{FirstSeenUtc:yyyy-MM-dd HH:mm:ss} UTC`");
        sb.AppendLine($"- **Last Observed**: `{LastSeenUtc:yyyy-MM-dd HH:mm:ss} UTC`");
        sb.AppendLine();
        sb.AppendLine("## 2. Affected Enterprise Locations");
        sb.AppendLine($"- **Total Facilities Impacted**: {AffectedFacilities.Count} ({string.Join(", ", AffectedFacilities)})");
        sb.AppendLine($"- **Total Lines Impacted**: {AffectedLines.Count}");
        foreach (string line in AffectedLines)
        {
            sb.AppendLine($"  - `{line}`");
        }
        sb.AppendLine();
        sb.AppendLine("## 3. Representative Stack Trace");
        sb.AppendLine("```csharp");
        sb.AppendLine(string.IsNullOrWhiteSpace(RepresentativeStackTrace) ? "(No stack trace captured)" : RepresentativeStackTrace);
        sb.AppendLine("```");
        sb.AppendLine();
        if (RecentIncidents.Count > 0)
        {
            var latest = RecentIncidents[^1];
            sb.AppendLine("## 4. Latest Incident Snapshot");
            sb.AppendLine($"- **Incident ID**: `{latest.IncidentId}`");
            sb.AppendLine($"- **Software Version**: `{latest.SoftwareVersion}`");
            sb.AppendLine($"- **Host OS / Runtime**: `{latest.SystemMetrics.Os}` / `.NET {latest.SystemMetrics.Clr}`");
            sb.AppendLine($"- **Process Memory**: `{latest.SystemMetrics.ProcessMemoryMb} MB`");
            sb.AppendLine($"- **Active Tool**: `{latest.PipelineContext.SafeToolLabel}`");
            sb.AppendLine();
        }
        sb.AppendLine("## 5. Required Claude Resolution");
        sb.AppendLine("This recurring defect affects multiple production lines across Sundaram plants.");
        sb.AppendLine("1. **Cluster Root Cause**: Explain the common failure pattern causing this across different machines.");
        sb.AppendLine("2. **Fix Proposal**: Provide the complete C# / C++ code modifications to permanently resolve this cluster.");
        sb.AppendLine("3. **Staged Rollout Advice**: Advise on rollout staging verification (Canary -> Pilot -> Staged -> GA).");

        return sb.ToString();
    }
}
