#!/usr/bin/env python3
"""Generate the Avalonia resources of Vision Studio and the browser dashboard's CSS from the design tokens.

    python3 tools/tokens/gen_tokens.py            # write Tokens.g.axaml and tokens.g.css
    python3 tools/tokens/gen_tokens.py --check    # exit 1 if a file is out of date

design/tokens/vision-tokens.json is the one source (ARCHITECTURE.md 2.3). Colours become
Color and SolidColorBrush resources per theme (Dark, Light, HighContrast); sizes, spacing,
radii and font sizes become theme-independent resources. Names: color.status.ok gives
Vs.Color.Status.Ok and Vs.Brush.Status.Ok; size.touch gives Vs.Size.Touch. Typefaces become
FontFamily resources (typeface.display gives Vs.Typeface.Display); a family embedded in Vision
Studio (EMBEDDED, Assets/Fonts) is named by its avares:// path, the fallbacks by family name.
The CSS (dotnet/Runtime.Host/Web/tokens.g.css) has the same names as custom properties:
--vs-color-status-ok, --vs-size-touch; dark on :root, light and high contrast on
:root[data-theme=light] and :root[data-theme=highContrast].
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "design/tokens/vision-tokens.json"
OUT = ROOT / "dotnet/Studio/Theme/Tokens.g.axaml"
CSS = ROOT / "dotnet/Runtime.Host/Web/tokens.g.css"
# Avalonia converts only its built-in variants from text; High contrast is App.HighContrast.
THEME_KEYS = {"dark": "Dark", "light": "Light", "highContrast": "{x:Static studio:App.HighContrast}"}
# Font files shipped in dotnet/Studio/Assets/Fonts (SIL Open Font License 1.1, requirements 17.15 NXT-02).
FONTS = "avares://vs-studio/Assets/Fonts"
EMBEDDED = {"Rajdhani", "Noto Sans", "JetBrains Mono"}


def pascal(word):
    return word[0].upper() + word[1:]


def colours(node, path):
    """Yield (name parts, {theme: value}) for every colour leaf."""
    if "dark" in node:
        yield path, node
        return
    for key, child in node.items():
        yield from colours(child, path + [pascal(key)])


def font_family(face):
    """Avalonia FontFamily text: the family, then its fallbacks, then the platform's default."""
    names = [face["family"], *face["fallback"]]
    return ", ".join(f"{FONTS}#{n}" if n in EMBEDDED else n for n in names) + ", $Default"


def css_font_family(face):
    return ", ".join(f'"{n}"' for n in [face["family"], *face["fallback"]]) + ", " + face["generic"]


def generate(tokens):
    lines = [
        "<!-- Generated by tools/tokens/gen_tokens.py from design/tokens/vision-tokens.json. Do not edit. -->",
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:studio="using:VisionSystem.Studio">',
    ]
    for group, prefix in (("size", "Size"), ("space", "Space"), ("font", "Font")):
        for key, value in tokens[group].items():
            lines.append(f'  <x:Double x:Key="Vs.{prefix}.{pascal(key)}">{value}</x:Double>')
    for key, value in tokens["space"].items():
        lines.append(f'  <Thickness x:Key="Vs.Pad.{pascal(key)}">{value}</Thickness>')
    lines.append(f'  <Thickness x:Key="Vs.Thickness.ImageFrame">{tokens["size"]["imageFrame"]}</Thickness>')
    for key, value in tokens["radius"].items():
        lines.append(f'  <CornerRadius x:Key="Vs.Radius.{pascal(key)}">{value}</CornerRadius>')
    for key, face in tokens["typeface"].items():
        lines.append(f'  <FontFamily x:Key="Vs.Typeface.{pascal(key)}">{font_family(face)}</FontFamily>')
    # the Fluent theme's own controls (text boxes, lists, tabs) read their face from this key
    lines.append(f'  <FontFamily x:Key="ContentControlThemeFontFamily">{font_family(tokens["typeface"]["body"])}</FontFamily>')
    leaves = list(colours(tokens["color"], []))
    lines.append("  <ResourceDictionary.ThemeDictionaries>")
    for theme in tokens["themes"]:
        lines.append(f'    <ResourceDictionary x:Key="{THEME_KEYS[theme]}">')
        for parts, values in leaves:
            name = ".".join(parts)
            lines.append(f'      <Color x:Key="Vs.Color.{name}">{values[theme]}</Color>')
            lines.append(f'      <SolidColorBrush x:Key="Vs.Brush.{name}" Color="{values[theme]}" />')
        lines.append("    </ResourceDictionary>")
    lines.append("  </ResourceDictionary.ThemeDictionaries>")
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


def kebab(word):
    return "".join("-" + c.lower() if c.isupper() else c for c in word)


def css_colour(value):
    """#AARRGGBB (the Avalonia form, alpha first) becomes rgba(); #RRGGBB stays."""
    if len(value) == 9:
        a, r, g, b = (int(value[i:i + 2], 16) for i in (1, 3, 5, 7))
        return f"rgba({r}, {g}, {b}, {a / 255:.3f})"
    return value


def generate_css(tokens):
    lines = ["/* Generated by tools/tokens/gen_tokens.py from design/tokens/vision-tokens.json. Do not edit. */"]
    leaves = list(colours(tokens["color"], []))
    for theme in tokens["themes"]:
        selector = ":root" if theme == "dark" else f':root[data-theme="{theme}"]'
        lines.append(selector + " {")
        if theme == "dark":
            for group in ("size", "space", "radius", "font"):
                for key, value in tokens[group].items():
                    unit = "" if isinstance(value, str) else "px"
                    lines.append(f"  --vs-{group}-{kebab(key)}: {value}{unit};")
            for key, face in tokens["typeface"].items():
                lines.append(f"  --vs-typeface-{kebab(key)}: {css_font_family(face)};")
        for parts, values in leaves:
            name = "-".join(kebab(p[0].lower() + p[1:]) for p in parts)
            lines.append(f"  --vs-color-{name}: {css_colour(values[theme])};")
        lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    tokens = json.loads(SRC.read_text(encoding="utf-8"))
    outputs = ((OUT, generate(tokens)), (CSS, generate_css(tokens)))
    if "--check" in sys.argv:
        stale = [p for p, text in outputs if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date: run python3 tools/tokens/gen_tokens.py")
        return 1 if stale else 0
    for p, text in outputs:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
